def _input_block(x, y, energy_type) -> dict:
    return {
        "energy_type": energy_type,
        "x_unit": "eV",
        "y_unit": "arbitrary (synthetic, counts-like)",
        "points": int(len(x)),
        "order": "descending" if x[0] > x[-1] else "ascending",
        "x": [float(v) for v in x],
        "y": [float(v) for v in y],
    }


def case_names() -> list[str]:
    return [*SINGLE_CASES, *SI2P_CASES]


def build_case(case: str) -> dict:
    return build_single(case) if case in SINGLE_CASES else build_si2p(case)


def _dump(obj, indent: int = 0) -> str:
    """JSON with one key per line and numeric arrays on a single line."""
    pad, inner = " " * indent, " " * (indent + 2)
    if isinstance(obj, dict):
        if not obj:
            return "{}"
        items = [f"{inner}{json.dumps(k)}: {_dump(v, indent + 2)}" for k, v in obj.items()]
        return "{\n" + ",\n".join(items) + f"\n{pad}}}"
    if isinstance(obj, list) and any(isinstance(v, (dict, list)) for v in obj):
        return "[\n" + ",\n".join(f"{inner}{_dump(v, indent + 2)}" for v in obj) + f"\n{pad}]"
    return json.dumps(obj, ensure_ascii=False, allow_nan=False)


def generate(source_commit: str) -> dict[str, bytes]:
    """All fixture files, by name, as bytes."""
    digest = source_sha256()
    provenance = {
        "generator": "tests/web_fixtures.py",
        "source_commit": source_commit,
        "source_files": list(SOURCE_FILES),
        "source_paths": source_paths(),
        "source_sha256": digest,
        "source_sha256_definition": (
            "sha256 of the lines '<sha256 hex>  <path relative to src/>' of the source "
            "files, sorted by path, each ending in a newline"
        ),
    }
    files, index = {}, []
    for case in case_names():
        data = build_case(case)
        data["provenance"] = provenance
        text = (_dump(data) + "\n").encode()
        files[f"{case}.json"] = text
        index.append({"case": case, "file": f"{case}.json", "model": data["model"]["name"],
                      "energy_type": data["input"]["energy_type"],
                      "sha256": hashlib.sha256(text).hexdigest()})
    files["index.json"] = (_dump({
        "schema": SCHEMA + "-index",
        "schema_version": SCHEMA_VERSION,
        "source_commit": source_commit,
        "source_sha256": digest,
        "cases": index,
    }) + "\n").encode()
    return files


def committed_source_commit() -> str | None:
    path = FIXTURE_DIR / "index.json"
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))["source_commit"]


def resolve_source_commit() -> str | None:
    """The exact commit from git when possible, else the committed index's.

    The fallback only applies where the history cannot answer (shallow CI
    clones, installs without git); ``source_sha256`` is still recomputed
    from the files, so a source change is detected there too.
    """
    return git_source_commit() or committed_source_commit()


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="rewrite tests/fixtures/web/")
    args = parser.parse_args(argv)
    if args.write:
        commit = git_source_commit()
        if commit is None:
            print("refusing to write: need a full git history and no uncommitted change to "
                  "the source files (commit them first)", file=sys.stderr)
            return 2
        FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
        files = generate(commit)
        for old in FIXTURE_DIR.glob("*.json"):
            if old.name not in files:
                old.unlink()
        for name, text in files.items():
            (FIXTURE_DIR / name).write_bytes(text)
        print(f"wrote {len(files)} files to {FIXTURE_DIR.relative_to(ROOT)} "
              f"(source {commit[:10]}, sha256 {source_sha256()[:12]})")
        return 0
    commit = resolve_source_commit()
    if commit is None:
        print("no fixtures written yet and no exact source commit available", file=sys.stderr)
        return 2
    files = generate(commit)
    on_disk = {p.name: p.read_bytes() for p in FIXTURE_DIR.glob("*.json")}
    stale = sorted(n for n in files.keys() | on_disk.keys() if files.get(n) != on_disk.get(n))
    if stale:
        print("stale fixtures (run: python -m tests.web_fixtures --write): " + ", ".join(stale))
        return 1
    print(f"{len(files)} fixture files are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())

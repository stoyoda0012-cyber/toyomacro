"""Language-neutral fixtures for ports of two fitting models.

A port of a toyomacro model to another runtime (a browser build under
Pyodide, for instance) needs to know what the model is supposed to return,
not only that it runs. This module writes that knowledge to
``tests/fixtures/web/`` as JSON, one file per case, from the same
generators the contract tests use:

- ``single_voigt_*`` -- one area-normalized ``toyomacro.lineshape.Voigt``
  on a background linear in energy, fitted jointly by unweighted least
  squares. toyomacro has no fitter for this model: the model, its bounds
  and the reference solver (SciPy ``least_squares``) are defined here, and
  only the lineshape -- ``Voigt.evaluate``, area-normalized, fwhm_g and
  fwhm_l -- is toyomacro's. Generated by :func:`make_single_voigt`, which
  follows the contract tests' style; its contract tests are new, in
  ``tests/test_web_fixtures.py``.
- ``si2p_oxide_*`` -- ``AutoFitter.fit_with_template(..., "Si2p_oxide")``
  on the spectrum of ``TestTemplateFitting.test_si2p_oxide_ke``
  (``tests/test_fitting_templates.py::_make_synthetic_si2p_ke``), on its
  own KE axis and on the BE axis, stored high-to-low. The two are the same
  numbers, not the same problem: toyomacro's discrete Shirley depends on
  the direction of the energy axis, so their optima differ (Si0 area by
  about 0.6 statistical sd).

Every input is synthetic. Each case carries the input spectrum, the model
settings, the generating parameters (``truth``), the least-squares optimum
of the model on that input (``expected``) with a tolerance per quantity,
and the toyomacro source it came from.

What ``expected`` and the tolerances mean
-----------------------------------------
``expected`` is the optimum of the model's objective on the stored input,
found by re-solving toyomacro's own residual with ftol = xtol = gtol =
1e-14. It is a property of the data and the model, not of a solver run, so
any correct implementation should land on it up to its termination test.
For the single-Voigt cases the "residual" is the one defined in this
module, not a toyomacro fitter.

A parameter's tolerance is ``10 * sqrt(2 * ftol * F * C_ii)`` with ftol =
1e-8 (SciPy's default, which both toyomacro and the ports use), F = 0.5 *
sum(residual**2) at the optimum and C = (J^T J)^-1 over the free
parameters. Moving parameter i by sqrt(2 * ftol * F * C_ii), the others
re-optimized, raises F by ftol * F -- the change the termination test
cannot see -- so the tolerance is ten times the width of that band. In
units of the linearized statistical standard deviation (also stored) it is
a few per cent. Other tolerances:

- cost F: relative 100 * ftol, the cost excess that matches the parameter
  tolerance;
- a parameter on a bound at the optimum: within 1e-7 * max(1, |bound|) of
  the bound, and the set of such parameters must match;
- the Shirley background (subtracted before the fit, so not a solver
  output): 1e-3 of the generating noise sigma.

``truth`` and ``expected`` differ by the noise and, for the Si 2p cases,
by model misspecification: the contract spectrum has a linear background
while the template subtracts a Shirley one, and its intermediate states'
widths do not lie on the template's width interpolation. Only cases whose
model matches their generator claim that the optimum is consistent with
the truth.

Reproducibility
---------------
Regenerating gives byte-identical files. Values are stored at a precision
fixed by their tolerance (one tenth of it), so platform-level floating
point differences do not change the bytes, and every expected value is
computed from the stored, rounded input.

``source_commit`` is the last commit that touched the numerical source
files listed in ``SOURCE_FILES`` (expanded in ``source_paths``);
``source_sha256`` is a digest of those files as they are on disk. Writing
requires a full (non-shallow) history and no uncommitted change to those
files, so the commit is exact when written. It is re-checked only where a
full history exists: a shallow clone (CI) checks ``source_sha256`` and the
bytes, and skips the commit check explicitly. Changing the numerical code
therefore means: commit it, then regenerate. Nothing else -- not the
package version -- enters the files.

Usage::

    python -m tests.web_fixtures           # check: compare with a fresh generation
    python -m tests.web_fixtures --write   # rewrite tests/fixtures/web/
"""


def source_paths() -> list[str]:
    """The files of ``SOURCE_FILES``, relative to src/, sorted."""
    out = []
    for entry in SOURCE_FILES:
        path = ROOT / "src" / entry
        if entry.endswith("/"):
            out += [f"{entry}{p.name}" for p in path.glob("*.py")]
        else:
            out.append(entry)
    return sorted(out)


def source_sha256() -> str:
    """SHA-256 of a ``sha256sum``-style listing of the source files.

    One line per file, ``<hex digest>  <path relative to src/>``, sorted by
    path. A port can recompute it from per-file digests alone.
    """
    listing = "".join(
        f"{hashlib.sha256((ROOT / 'src' / p).read_bytes()).hexdigest()}  {p}\n"
        for p in source_paths()
    )
    return hashlib.sha256(listing.encode()).hexdigest()


def _git(*args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(ROOT), *args], capture_output=True, text=True, check=True,
    ).stdout.strip()


def git_source_commit() -> str | None:
    """Last commit touching the source files, or None when it cannot be exact.

    None for a shallow clone (CI), a tree without git, or uncommitted
    changes to the source files.
    """
    paths = [f"src/{entry}" for entry in SOURCE_FILES]
    try:
        if _git("rev-parse", "--is-shallow-repository") != "false":
            return None
        if _git("status", "--porcelain", "--", *paths):
            return None
        return _git("log", "-1", "--format=%H", "--", *paths) or None
    except (OSError, subprocess.CalledProcessError):
        return None


# ----------------------------------------------------------------------
# Rounding: storage precision follows the tolerance
# ----------------------------------------------------------------------

def _round_sig_up(value: float, digits: int = 2) -> float:
    """Round a positive tolerance up to ``digits`` significant digits."""
    exponent = math.floor(math.log10(value)) - digits + 1
    return float(round(math.ceil(value / 10.0**exponent) * 10.0**exponent, max(0, -exponent)))


def _round_sig(value: float, digits: int) -> float:
    if value == 0 or not math.isfinite(value):
        return float(value)
    return float(round(value, digits - 1 - math.floor(math.log10(abs(value)))))


def _decimals_for(tolerance: float) -> int:
    """Decimal places that store a value to a tenth of its tolerance."""
    return -math.floor(math.log10(tolerance / 10.0))


def _round_to(value: float, decimals: int) -> float:
    out = float(round(value, decimals))
    return 0.0 if out == 0 else out  # no "-0.0" in the files


def _round_array(values, decimals: int) -> list[float]:
    return [_round_to(float(v), decimals) for v in values]


# ----------------------------------------------------------------------
# Solver capture (test-time only; the numerical source is not touched)
# ----------------------------------------------------------------------

@contextlib.contextmanager
def capture_least_squares(**override):
    """Record (and optionally override settings of) scipy least_squares calls.

    ``_fast_template_fit`` imports ``least_squares`` from ``scipy.optimize``
    at call time, so replacing the module attribute reaches it.
    """
    calls: list[tuple[scipy.optimize.OptimizeResult, dict]] = []
    original = scipy.optimize.least_squares

    def wrapped(fun, x0, **kwargs):
        kwargs.update(override)
        solution = original(fun, x0, **kwargs)
        calls.append((solution, kwargs))
        return solution

    scipy.optimize.least_squares = wrapped
    try:
        yield calls
    finally:
        scipy.optimize.least_squares = original


def _active(x, lower, upper) -> list[str | None]:
    out = []
    for v, lo, hi in zip(x, lower, upper, strict=True):
        if math.isfinite(lo) and abs(v - lo) <= BOUND_RTOL * max(1.0, abs(lo)):
            out.append("lower")
        elif math.isfinite(hi) and abs(v - hi) <= BOUND_RTOL * max(1.0, abs(hi)):
            out.append("upper")
        else:
            out.append(None)
    return out


def _conditional_variance_factors(jac: np.ndarray, active: list[str | None]) -> np.ndarray:
    """diag((J^T J)^-1) over the free parameters (NaN for bound ones).

    Columns are scaled to unit norm before the inverse so that areas
    (~1e4) and widths (~0.1) do not set the conditioning.
    """
    free = np.array([a is None for a in active])
    jf = jac[:, free]
    norms = np.linalg.norm(jf, axis=0)
    scaled = jf / norms
    out = np.full(jac.shape[1], np.nan)
    out[free] = np.diag(np.linalg.pinv(scaled.T @ scaled)) / norms**2
    return out


def _parameter_entries(names, units, values, active, bounds, cost, factors, sigma):
    entries = []
    for name, unit, v, side, (lo, hi), c in zip(
        names, units, values, active, bounds, factors, strict=True,
    ):
        if side is None:
            tol = _round_sig_up(SAFETY * math.sqrt(2.0 * FTOL * cost * c))
            sd = _round_sig(sigma * math.sqrt(c), 2)
            bound = None
        else:
            bound = lo if side == "lower" else hi
            tol = BOUND_RTOL * max(1.0, abs(bound))  # a constant: not rounded
            sd = None
        entries.append({
            "name": name,
            "unit": unit,
            "value": _round_to(v, _decimals_for(tol)),
            "tolerance": tol,
            "statistical_sd": sd,
            "at_bound": side,
            "bound": bound,
        })
    return entries


def _tolerance_block(extra: dict) -> dict:
    return {
        "rule": (
            "free parameter: 10*sqrt(2*ftol*F*C_ii), ftol=1e-8 (SciPy default), "
            "F=0.5*sum(residual^2) at the optimum, C=(J^T J)^-1 over the free parameters; "
            "parameter at a bound: within 1e-7*max(1,|bound|) of it; "
            "cost: relative 100*ftol"
        ),
        "ftol": FTOL,
        "safety_factor": SAFETY,
        "cost_relative": 100.0 * FTOL,
        "bound_relative": BOUND_RTOL,
        **extra,
    }


